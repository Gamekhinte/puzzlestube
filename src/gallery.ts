export const galleryThumb = (g: GalleryImage) => `galerie/${g.file}-k.jpg`

export function loadGallery(g: GalleryImage): Promise<HTMLCanvasElement> {
  return new Promise((res, rej) => {
    const im = new Image()
    im.onload = () => {
      const cv = document.createElement('canvas')
      cv.width = im.naturalWidth; cv.height = im.naturalHeight
      cv.getContext('2d')!.drawImage(im, 0, 0)
      res(cv)
    }
    im.onerror = () => rej(new Error('Das Bild konnte nicht geladen werden.'))
    im.src = `galerie/${g.file}.jpg`
  })
}
